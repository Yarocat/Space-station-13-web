let objectIdCounter = 100;

export function createWorldObject(type: StructureType | ItemType, overrides: Partial<WorldObject> = {}): WorldObject {
  const isItem = type in ITEMS_REGISTRY;
  const meta = isItem ? ITEMS_REGISTRY[type as ItemType] : STRUCTURES_REGISTRY[type as StructureType];
  
  const id = `obj_${Date.now()}_${++objectIdCounter}`;
  const isDoor = type.includes('Door');
  const isContainer = type === 'Closet' || type === 'SecurityLocker';

  return {
    id,
    type,
    name: meta ? meta.name : type,
    isItem,
    isOpen: isDoor || isContainer ? false : undefined,
    isLocked: type === 'SecurityDoor' || type === 'SecurityLocker' ? false : undefined,
    welded: false,
    anchored: !isItem,
    charges: meta && meta.defaultCharges !== undefined ? meta.defaultCharges : undefined,
    maxCharges: meta && meta.defaultCharges !== undefined ? meta.defaultCharges : undefined,
    color: meta ? meta.color : '#94a3b8',
    icon: meta ? meta.symbol : '?',
    description: meta ? meta.description : '',
    contains: isContainer ? [] : undefined,
    ...overrides,
  };
}
